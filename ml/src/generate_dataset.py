# Deduplicate
for intent, utterances in intents_data.items():
    intents_data[intent] = list(set(utterances))

all_examples = []
for intent, utterances in intents_data.items():
    for text in utterances:
        all_examples.append({"text": text, "intent": intent})

random.shuffle(all_examples)

total = len(all_examples)
train_split = int(0.7 * total)
val_split = int(0.15 * total)

train_data = all_examples[:train_split]
val_data = all_examples[train_split:train_split+val_split]
test_data = all_examples[train_split+val_split:]

print(f"Total examples: {total}")
print(f"Train: {len(train_data)}")
print(f"Validation: {len(val_data)}")
print(f"Test: {len(test_data)}")

with open('ml/data/intents.json', 'w') as f:
    json.dump(intents_data, f, indent=2)

with open('ml/data/splits/train.json', 'w') as f:
    json.dump(train_data, f, indent=2)

with open('ml/data/splits/validation.json', 'w') as f:
    json.dump(val_data, f, indent=2)

with open('ml/data/splits/test.json', 'w') as f:
    json.dump(test_data, f, indent=2)

print("Dataset generated successfully.")
